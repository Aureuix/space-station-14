[GenerateTypedNameReferences]
public sealed partial class HandLabelerWindow : DefaultWindow
// Kin Bin End
{
    // Kin Bin Begin
    [Dependency] private IConfigurationManager _cfg = default!;
    [Dependency] private IClipboardManager _clipboard = default!;
    [Dependency] private ILogManager _logManager = default!;
    // Kin Bin End

    public event Action<string>? OnLabelChanged;
    public event Action<string>? OnLabelSelected; // Starlight

    /// <summary>
    /// Is the user currently entering text into the control?
    /// </summary>
    private bool _focused;
    // TODO LineEdit Make this a bool on the LineEdit control

    private string _label = string.Empty;
    private string _initialLabel = string.Empty;

    // Kin Bin Begin
    private List<LabelTab> _savedLabels = [];
    private List<string> _savedLabelsSorted = [];
    private string _savedLabelSelected = string.Empty;
    private int _currentTab = 0;
    private bool _paperLoaded = false;
    private LabelSortingType _sortingState;
    private ISawmill _sawmill = default!;
    // Kin Bin End

    public HandLabelerWindow()
    {
        RobustXamlLoader.Load(this);

        // Kin Bin Begin
        IoCManager.InjectDependencies(this); 
        _sawmill = _logManager.GetSawmill("STARLIGHT.handlabeler");
        LoadCVar();
        ViewUpdate();
        // Kin Bin End

        // TODO: Generic "input label" text when box empty
        LabelLineEdit.OnTextChanged += e =>
        {
            _label = e.Text;
            OnLabelChanged?.Invoke(_label);
            // Kin Bin Begin
            UpdatePreview();
            // Kin Bin End
        };

        LabelLineEdit.OnFocusEnter += _ => _focused = true;
        LabelLineEdit.OnFocusExit += _ =>
        {
            _focused = false;
            LabelLineEdit.Text = _label;
        };

        ResetLabelButton.OnPressed += _ => LabelLineEdit.SetText(_savedLabelSelected, true);
        ClearLabelButton.OnPressed += _ => LabelLineEdit.SetText("", true);

        // Kin Bin Begin: Buttons
        NewLabelButton.OnPressed += _ => LabelAdd();
        SortLabelButton.OnPressed += _ => ButtonSort();
        LabelTabsListButton.OnItemSelected += _ =>
        {
            LabelTabsListButton.SelectId(_.Id);
            _currentTab = _.Id;
            ViewUpdate();
        };
        LabelTabsEditButton.OnPressed += _ =>
        {
            HandLabelerTabsPopup popup = new HandLabelerTabsPopup(this, _savedLabels);
            this.AddChild(popup);
            popup.Open(UIBox2.FromDimensions(this.Position, new Vector2(this.Width, this.Height)));
        };
        // Kin Bin End
    }

    public void SetMaxLabelLength(int maxLength) => LabelLineEdit.IsValid = s => s.Length <= maxLength;

    public void SetCurrentLabel(string label)
    {
        _label = label;
        if (!_focused)
        {
            LabelLineEdit.Text = label;
        }
        UpdatePreview(); // Kin Bin: Update label preview panel
    }
    public void SetInitialLabelState()
    {
        LabelLineEdit.Text = _label;
        LabelLineEdit.CursorPosition = _label.Length;
        LabelLineEdit.SelectionStart = 0;
        _initialLabel = _label;
        UpdatePreview(); //  Kin Bin: Update label preview panel
    }

    // Kin Bin Begin
    public void UpdatePreview()
    {
        string limitColor = _label.Length < 50 ? "FFAAFF" : "FF0000";
        CurrentLabelChars.Text = $"[color=#{limitColor}]{_label.Length} / 50[/color]";
        CurrentLabelPreview.Text = _label;
    }
    public void TabRename(string tabname, int idx)
    {
        LabelTabsListButton.SetItemText(idx, tabname);
        _savedLabels[idx] = new LabelTab(tabname, _savedLabels[idx].tab);
        SaveCVar();
        ViewUpdate();
    }
    public void TabAdd()
    {
        _savedLabels.Add(new LabelTab("New Tab", []));
        SaveCVar();
        TabUpdate();
    }
    public void TabRemove(int idx)
    {
        _savedLabels.RemoveAt(idx);
        if (idx <= _currentTab)
        {
            --_currentTab;
        }
        SaveCVar();
        TabUpdate();
    }
    public void TabUpdate()
    {
        LabelTabsListButton.Clear();
        for (int tab = 0; tab < _savedLabels.Count; tab++)
        {
            LabelTabsListButton.AddItem(_savedLabels[tab].name, tab);
        }
        LabelTabsListButton.Select(_currentTab);
    }



    // Labels list handling
    public void LabelAdd()
    {
        if (!string.IsNullOrWhiteSpace(_label) && !_savedLabels[_currentTab].tab.Contains(_label))
        {
            var sanitized = FormattedMessage.FromMarkupPermissive(_label)
                    .SanitizeWhitelist(FormattedMessageSanitizer.ItemLabelTags)
                    .ToMarkup();
            _savedLabels[_currentTab].tab.Add(sanitized);
            SaveCVar();
            ViewUpdate();
        }
    }
    public void LabelRemove(string label)
    {
        _savedLabels[_currentTab].tab.Remove(label);
        SaveCVar();
        ViewUpdate();
    }
    public void ViewUpdate()
    {
        SavedLabelsContainer.RemoveAllChildren();
        ViewSort();
        foreach (string label in _savedLabelsSorted)
        {
            if (label != string.Empty)
            {
                Button labelDelete = new Button()
                {
                    Name = label,
                    Children = { new RichTextLabel() { Text = "X", Margin = new Thickness(-7, -2, 0, 0) } },
                    SetWidth = 14,
                    StyleClasses = { StyleClass.ButtonSquare }
                };
                Button labelButton = new Button()
                {
                    StyleBoxOverride = new StyleBoxFlat
                    {
                        BackgroundColor = Color.FromHex("#7B7A6C"),
                    },
                    HorizontalExpand = true,
                    Margin = new Thickness(-1, 0, 0, 0),
                    Children = { new RichTextLabel() { Text = label, Margin = new Thickness(5, 1, 1, 1) } }
                };
                BoxContainer labelEntry = new BoxContainer()
                {
                    Orientation = BoxContainer.LayoutOrientation.Horizontal,
                    Margin = new Thickness(1),
                    SetHeight = 25,
                    Children =
                {
                    labelDelete,
                    labelButton
                }
                };
                SavedLabelsContainer.AddChild(labelEntry);

                // Handle buttonpresses

                labelButton.OnPressed += _ =>
                {
                    OnLabelSelected?.Invoke(label);
                    _savedLabelSelected = label;
                    SetCurrentLabel(label);
                };
                labelDelete.OnPressed += _ => LabelRemove(label);
            }
        }
    }
        
    public void ButtonSort()
    {
        _sortingState++;
        if (_sortingState > LabelSortingType.Newest)
            _sortingState = LabelSortingType.None;
        SortLabelButton.Text = _sortingState switch
        {
            LabelSortingType.Alphabetical => Loc.GetString("hand-labeler-sort-label-alphabetical"),
            LabelSortingType.Length => Loc.GetString("hand-labeler-sort-label-length"),
            LabelSortingType.Newest => Loc.GetString("hand-labeler-sort-label-newest"),
            _ => Loc.GetString("hand-labeler-sort-label-none")
        };
        ViewUpdate();
    }
    // Todo for P2: "can merge these two v^" (but I don't remember what my plan was)
    public void ViewSort() => _savedLabelsSorted = _sortingState switch
    {
        LabelSortingType.Alphabetical => _savedLabels[_currentTab].tab.OrderBy(x => x).ToList(),
        LabelSortingType.Length => _savedLabels[_currentTab].tab.OrderByDescending(x => x.Length).ToList(),
        LabelSortingType.Newest => Enumerable.Reverse(_savedLabels[_currentTab].tab).ToList(),
        _ => _savedLabels[_currentTab].tab,
    };
    private void LoadCVar()
    {
        var tabsRaw = new List<string>(_cfg.GetCVar(StarlightCCVars.HandLabelerSavedLabels).Split("\u0085Tab: "));

        for (int i = 0; i < tabsRaw.Count; i++)
        {
            var tabSplit = tabsRaw[i].Split('\n', StringSplitOptions.RemoveEmptyEntries).ToList();
            var tabName = "";
            if (i == 0)
            {
                tabName = "Saved Tabs";
            }
            else
            {
                tabName = !string.IsNullOrWhiteSpace(tabSplit[0]) ? tabSplit[0] : $"Saved Tab #{i + 1}";
                tabSplit.RemoveAt(0);
            }
            tabSplit.ForEach(label => label = FormattedMessage.FromMarkupPermissive(label)
                    .SanitizeWhitelist(FormattedMessageSanitizer.ItemLabelTags)
                    .ToMarkup());
            _savedLabels.Add(new LabelTab(tabName, tabSplit));
        }
        TabUpdate();
        ViewUpdate();
    }
    public void SaveCVar()
    {
        string tabsRaw = "";
        for (int i = 0; i < _savedLabels.Count; i++)
        {
            tabsRaw += (i > 0 ? $"\u0085Tab: {_savedLabels[i].name}\n" : "") + $"{string.Join('\n', _savedLabels[i].tab)}\n";
        }
        _cfg.SetCVar(StarlightCCVars.HandLabelerSavedLabels, tabsRaw);
        _cfg.SaveToFile();
    }
    private enum LabelSortingType : byte
    {
        None = 0,
        Alphabetical = 1,
        Length = 2,
        Newest = 3,
    }
    public struct LabelTab(string _name, List<string> _labels)
    {
        public string name = _name;
        public List<string> tab = _labels;
    }

    // Kin Bin End
}
