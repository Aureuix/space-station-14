namespace Content.Client.Labels.UI;

[GenerateTypedNameReferences]
public sealed partial class HandLabelerTabsPopup : Popup
{
    [Dependency] private IEntitySystemManager _entitySystem = default!;

    private HandLabelerWindow _labelerWindow;
    private List<LabelTab> _tabList;
    private int _activeButton = 0;
    public HandLabelerTabsPopup(HandLabelerWindow window, List<LabelTab> tabs)
    {
        _labelerWindow = window;
        _tabList = tabs;
        RobustXamlLoader.Load(this);
        IoCManager.InjectDependencies(this);
        ViewUpdate();
        ClosePopup.OnPressed += _ => this.Close();
        NewTab.OnPressed += _ =>
        {
            window.TabAdd();
            ViewUpdate();
        };
    }
    public void ViewUpdate()
    {
        Tabs.RemoveAllChildren();
        if (_tabList.Count == 1)
        {
            RichTextLabel noTabs = new RichTextLabel()
            {
                Text = Loc.GetString("hand-labeler-popup-rename-filler"),
                Margin = new Thickness(0, 10, 0, 0),
                HorizontalAlignment = HAlignment.Center
            };
            Tabs.AddChild(noTabs);
        }
        for (int tab = 1; tab < _tabList.Count(); tab++)
        {
            {
                int tabidx = tab;
                Button tabDelete = new Button()
                {
                    Disabled = _activeButton != tab && _activeButton != 0,
                    Pressed = _activeButton == tab,
                    Children = { new RichTextLabel() { Text = "X", Margin = new Thickness(-7, -2, 0, 0) } },
                    SetWidth = 14,
                    StyleClasses = { StyleClass.ButtonSquare },
                    HorizontalAlignment = HAlignment.Left,
                };
                LineEdit tabInput = new LineEdit
                {
                    Text = _tabList[tab].name,
                    Margin = new Thickness(14, 0, 0, 0)
                };
                PanelContainer listItem = new PanelContainer
                {
                    Margin = new Thickness(2, 2, 2, 2),
                    SetHeight = 30,
                    PanelOverride = new StyleBoxFlat { BackgroundColor = Color.FromHex("#272730") },
                    VerticalAlignment = VAlignment.Top,
                    HorizontalExpand = true,
                    Children =
                    {
                        tabDelete,
                        tabInput
                    },
                };
                Tabs.AddChild(listItem);

                // Handle buttonpresses

                tabInput.OnTextChanged += _ => _labelerWindow.TabRename(_.Text, tabidx);
                tabDelete.OnPressed += _ =>
                {
                    if (!tabDelete.Pressed)
                    {
                        TabRemoveConfirm(tabidx, tabDelete);
                    }
                };
            }
        }
    }
    public void TabRemoveConfirm(int tabidx, Button button)
    {
        Popup popup = new Popup();
        Label warning = new Label()
        {
            Margin = new Thickness(10),
            Text = Loc.GetString("hand-labeler-popup-removal-warning"),
            HorizontalAlignment = HAlignment.Center
        };
        Button confirm = new Button()
        {
            Text = Loc.GetString("hand-labeler-popup-delete-confirm"),
        };
        Button deny = new Button()
        {
            Text = Loc.GetString("hand-labeler-popup-delete-decline"),
        };
        BoxContainer buttons = new BoxContainer()
        {
            Margin = new Thickness(10, 0, 10, 0),
            Orientation = BoxContainer.LayoutOrientation.Horizontal,
            VerticalAlignment = VAlignment.Bottom,
            HorizontalExpand = true,
            Children =
            {
                confirm,
                //Because button horizontal alignment is a lie apparently
                new Control { HorizontalExpand = true },
                deny,
            }
        };
        BoxContainer container = new BoxContainer()
        {
            Orientation = BoxContainer.LayoutOrientation.Vertical,
            VerticalExpand = true,
            Children =
            {
                warning,
                buttons,
            }
        };
        PanelContainer panel = new PanelContainer
        {
            SetSize = new Vector2(400, 80),
            PanelOverride = new StyleBoxFlat
            {
                BorderThickness = new Thickness(3),
                BorderColor = Color.FromHex("#545455"),
                BackgroundColor = Color.FromHex("#25252a"),
            },
            MouseFilter = MouseFilterMode.Stop,
            Children =
            {
                container
            }
        };
        popup.AddChild(panel);
        popup.CloseOnClick = false;
        _activeButton = tabidx;
        ViewUpdate();
        this.AddChild(popup);
        popup.Open();


        // Handle buttonpresses

        confirm.OnPressed += _ =>
        {
            _labelerWindow.TabRemove(tabidx);
            _activeButton = 0;
            ViewUpdate();
            popup.Close();
        };
        deny.OnPressed += _ =>
        {
            _activeButton = 0;
            ViewUpdate();
            popup.Close();
        };
    }
}
